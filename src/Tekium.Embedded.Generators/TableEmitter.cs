using System.Globalization;
using System.Text;

namespace Tekium.Embedded.Generators;

/// <summary>Writes the serializer of one table as C# source.</summary>
internal static class TableEmitter
{
    private const string Root = "global::Tekium.Embedded.";

    public static string Emit(TableModel table)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("// Generated by TekiumDB from the [TkTable] attribute. Changes to this file are lost.");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        if (table.Namespace is not null)
        {
            source.Append("namespace ").AppendLine(table.Namespace);
            source.AppendLine("{");
        }

        foreach (var outer in table.ContainingTypes)
        {
            source.AppendLine(outer);
            source.AppendLine("{");
        }

        var row = $"{Root}ITkRow<{table.Name}>";
        source.Append(table.Declaration).Append(" : ").AppendLine(row);
        source.AppendLine("{");

        source.AppendLine($"    private static readonly {Root}TkColumn[] __tkColumns = new {Root}TkColumn[]");
        source.AppendLine("    {");
        foreach (var column in table.Columns)
        {
            source.AppendLine(
                $"        new {Root}TkColumn({Literal(column.ColumnName)}, {Root}TkColumnType.{column.StoreType}, {(column.IsNullable ? "true" : "false")}),");
        }

        source.AppendLine("    };");
        source.AppendLine();
        source.AppendLine($"    static string {row}.TableName => {Literal(table.TableName)};");
        source.AppendLine();
        source.AppendLine($"    static global::System.ReadOnlySpan<{Root}TkColumn> {row}.Columns => __tkColumns;");
        source.AppendLine();
        source.AppendLine($"    static int {row}.KeyColumn => {table.KeyColumn.ToString(CultureInfo.InvariantCulture)};");
        source.AppendLine();

        EmitWrite(source, table, row);
        EmitRead(source, table, row);

        var key = table.Columns[table.KeyColumn];
        source.AppendLine($"    static int {row}.WriteKey({table.Name} row, global::System.Span<byte> destination) =>");
        source.AppendLine($"        {Root}TkKey.Write({NotNull(key, "row." + key.Property)}, destination);");
        source.AppendLine("}");

        foreach (var unused in table.ContainingTypes)
        {
            source.AppendLine("}");
        }

        if (table.Namespace is not null)
        {
            source.AppendLine("}");
        }

        return source.ToString();
    }

    private static void EmitWrite(StringBuilder source, TableModel table, string row)
    {
        source.AppendLine($"    static void {row}.Write(ref {Root}TkRowWriter writer, {table.Name} row)");
        source.AppendLine("    {");
        for (var i = 0; i < table.Columns.Count; i++)
        {
            var column = table.Columns[i];
            var access = "row." + column.Property;
            if (!column.IsNullable)
            {
                source.AppendLine($"        writer.Write{column.Method}({Stored(column, NotNull(column, access))});");
                continue;
            }

            var local = "__v" + i.ToString(CultureInfo.InvariantCulture);
            source.AppendLine($"        if ({access} is {{ }} {local})");
            source.AppendLine("        {");
            source.AppendLine($"            writer.Write{column.Method}({Stored(column, local)});");
            source.AppendLine("        }");
            source.AppendLine("        else");
            source.AppendLine("        {");
            source.AppendLine("            writer.WriteNull();");
            source.AppendLine("        }");
        }

        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void EmitRead(StringBuilder source, TableModel table, string row)
    {
        source.AppendLine($"    static {table.Name} {row}.Read(ref {Root}TkRowReader reader)");
        source.AppendLine("    {");
        for (var i = 0; i < table.Columns.Count; i++)
        {
            var column = table.Columns[i];
            var local = "__v" + i.ToString(CultureInfo.InvariantCulture);
            var initial = column switch
            {
                { IsNullable: true } => "default",
                { StoreType: "Text" } => "\"\"",
                { StoreType: "Bytes" } => "global::System.Array.Empty<byte>()",
                _ => "default",
            };
            source.AppendLine($"        {column.PropertyType}{(column.IsNullable ? "?" : string.Empty)} {local} = {initial};");
        }

        source.AppendLine("        while (reader.Next(out var member))");
        source.AppendLine("        {");
        source.AppendLine("            switch (member)");
        source.AppendLine("            {");
        for (var i = 0; i < table.Columns.Count; i++)
        {
            var column = table.Columns[i];
            var local = "__v" + i.ToString(CultureInfo.InvariantCulture);
            var read = $"reader.Read{column.Method}()";
            if (column.IsEnum)
            {
                read = $"({column.PropertyType}){read}";
            }

            source.AppendLine($"                case {i.ToString(CultureInfo.InvariantCulture)}:");
            source.AppendLine(column.IsNullable
                ? $"                    {local} = reader.IsNull ? default({column.PropertyType}?) : {read};"
                : $"                    {local} = {read};");
            source.AppendLine("                    break;");
        }

        source.AppendLine("            }");
        source.AppendLine("        }");
        source.AppendLine();
        source.AppendLine($"        return new {table.Name}");
        source.AppendLine("        {");
        for (var i = 0; i < table.Columns.Count; i++)
        {
            source.AppendLine($"            {table.Columns[i].Property} = __v{i.ToString(CultureInfo.InvariantCulture)},");
        }

        source.AppendLine("        };");
        source.AppendLine("    }");
        source.AppendLine();
    }

    /// <summary>A reference that must not be null says which property it was when it is.</summary>
    private static string NotNull(ColumnModel column, string access) =>
        column.IsValueType
            ? access
            : $"({access} ?? throw new global::System.ArgumentNullException({Literal(column.Property.TrimStart('@'))}, \"A column that is not nullable has no value.\"))";

    private static string Stored(ColumnModel column, string value) =>
        column.IsEnum ? $"({column.StoredAs}){value}" : value;

    private static string Literal(string value)
    {
        var literal = new StringBuilder("\"");
        foreach (var character in value)
        {
            literal.Append(character switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                < ' ' or (char)0x2028 or (char)0x2029 => "\\u" + ((int)character).ToString("x4", CultureInfo.InvariantCulture),
                _ => character.ToString(),
            });
        }

        return literal.Append('"').ToString();
    }
}

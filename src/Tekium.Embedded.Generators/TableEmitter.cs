using System.Globalization;
using System.Text;

namespace Tekium.Embedded.Generators;

/// <summary>Writes the serializer of one table as C# source.</summary>
internal static class TableEmitter
{
    private const string Root = "global::Tekium.Embedded.";

    public static string Emit(TableModel table)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("// Generated by TekiumDB from the [TkTable] attribute. Changes to this file are lost.");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        if (table.Namespace is not null)
        {
            source.Append("namespace ").AppendLine(table.Namespace);
            source.AppendLine("{");
        }

        foreach (var outer in table.ContainingTypes)
        {
            source.AppendLine(outer);
            source.AppendLine("{");
        }

        var row = $"{Root}ITkRow<{table.Name}>";
        source.Append(table.Declaration).Append(" : ").AppendLine(row);
        source.AppendLine("{");

        source.AppendLine($"    private static readonly {Root}TkColumn[] __tkColumns = new {Root}TkColumn[]");
        source.AppendLine("    {");
        foreach (var column in table.Columns)
        {
            source.AppendLine(
                $"        new {Root}TkColumn({Literal(column.ColumnName)}, {Root}TkColumnType.{column.StoreType}, {(column.IsNullable ? "true" : "false")}),");
        }

        source.AppendLine("    };");
        source.AppendLine();
        source.AppendLine($"    static string {row}.TableName => {Literal(table.TableName)};");
        source.AppendLine();
        source.AppendLine($"    static global::System.ReadOnlySpan<{Root}TkColumn> {row}.Columns => __tkColumns;");
        source.AppendLine();
        source.AppendLine($"    static int {row}.KeyColumn => {table.KeyColumn.ToString(CultureInfo.InvariantCulture)};");
        source.AppendLine();

        EmitWrite(source, table, row);
        EmitRead(source, table, row);

        var key = table.Columns[table.KeyColumn];
        source.AppendLine($"    static int {row}.WriteKey({table.Name} row, global::System.Span<byte> destination) =>");
        source.AppendLine($"        {Root}TkKey.Write({NotNull(key, "row." + key.Property)}, destination);");
        source.AppendLine();
        EmitFields(source, table, row);
        source.AppendLine("}");

        foreach (var unused in table.ContainingTypes)
        {
            source.AppendLine("}");
        }

        if (table.Namespace is not null)
        {
            source.AppendLine("}");
        }

        return source.ToString();
    }

    private static void EmitWrite(StringBuilder source, TableModel table, string row)
    {
        source.AppendLine($"    static void {row}.Write(ref {Root}TkRowWriter writer, {table.Name} row)");
        source.AppendLine("    {");
        for (var i = 0; i < table.Columns.Count; i++)
        {
            var column = table.Columns[i];
            var access = "row." + column.Property;
            if (!column.IsNullable)
            {
                source.AppendLine($"        writer.Write{column.Method}({Stored(column, NotNull(column, access))});");
                continue;
            }

            var local = "__v" + i.ToString(CultureInfo.InvariantCulture);
            source.AppendLine($"        if ({access} is {{ }} {local})");
            source.AppendLine("        {");
            source.AppendLine($"            writer.Write{column.Method}({Stored(column, local)});");
            source.AppendLine("        }");
            source.AppendLine("        else");
            source.AppendLine("        {");
            source.AppendLine("            writer.WriteNull();");
            source.AppendLine("        }");
        }

        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void EmitRead(StringBuilder source, TableModel table, string row)
    {
        source.AppendLine($"    static {table.Name} {row}.Read(ref {Root}TkRowReader reader)");
        source.AppendLine("    {");
        for (var i = 0; i < table.Columns.Count; i++)
        {
            var column = table.Columns[i];
            var local = "__v" + i.ToString(CultureInfo.InvariantCulture);
            var initial = column switch
            {
                { IsNullable: true } => "default",
                { StoreType: "Text" } => "\"\"",
                { StoreType: "Bytes" } => "global::System.Array.Empty<byte>()",
                _ => "default",
            };
            source.AppendLine($"        {column.PropertyType}{(column.IsNullable ? "?" : string.Empty)} {local} = {initial};");
        }

        source.AppendLine("        while (reader.Next(out var member))");
        source.AppendLine("        {");
        source.AppendLine("            switch (member)");
        source.AppendLine("            {");
        for (var i = 0; i < table.Columns.Count; i++)
        {
            var column = table.Columns[i];
            var local = "__v" + i.ToString(CultureInfo.InvariantCulture);
            var read = $"reader.Read{column.Method}()";
            if (column.IsEnum)
            {
                read = $"({column.PropertyType}){read}";
            }

            source.AppendLine($"                case {i.ToString(CultureInfo.InvariantCulture)}:");
            source.AppendLine(column.IsNullable
                ? $"                    {local} = reader.IsNull ? default({column.PropertyType}?) : {read};"
                : $"                    {local} = {read};");
            source.AppendLine("                    break;");
        }

        source.AppendLine("            }");
        source.AppendLine("        }");
        source.AppendLine();
        source.AppendLine($"        return new {table.Name}");
        source.AppendLine("        {");
        for (var i = 0; i < table.Columns.Count; i++)
        {
            source.AppendLine($"            {table.Columns[i].Property} = __v{i.ToString(CultureInfo.InvariantCulture)},");
        }

        source.AppendLine("        };");
        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void EmitFields(StringBuilder source, TableModel table, string row)
    {
        var fields = table.Columns.Concat(table.Computed).ToList();

        source.AppendLine("    /// <summary>The columns and indexed expressions of the table, to write conditions with.</summary>");
        source.AppendLine("#pragma warning disable CS0108 // A property may be named like a member of object.");
        source.AppendLine("    public static class Fields");
        source.AppendLine("    {");
        for (var i = 0; i < fields.Count; i++)
        {
            var field = fields[i];
            source.AppendLine($"        /// <summary>The field of <see cref=\"{table.Name}.{field.Property}\"/>.</summary>");
            source.AppendLine(
                $"        public static readonly {Root}TkField<{table.Name}, {field.PropertyType}> {field.Property} = new {Root}TkField<{table.Name}, {field.PropertyType}>({i.ToString(CultureInfo.InvariantCulture)}, {Root}TkColumnType.{field.StoreType}, {(field.IsNullable ? "true" : "false")});");
        }

        source.AppendLine("    }");
        source.AppendLine("#pragma warning restore CS0108");
        source.AppendLine();
        source.AppendLine($"    static {Root}TkField<{table.Name}>? {row}.FindField(string name) => name switch");
        source.AppendLine("    {");
        foreach (var field in fields)
        {
            source.AppendLine($"        \"{field.Property}\" => Fields.{field.Property},");
        }

        source.AppendLine("        _ => null,");
        source.AppendLine("    };");
        source.AppendLine();

        if (table.Computed.Count > 0)
        {
            source.AppendLine($"    private static readonly {Root}TkExpression[] __tkExpressions = new {Root}TkExpression[]");
            source.AppendLine("    {");
            foreach (var computed in table.Computed)
            {
                source.AppendLine(
                    $"        new {Root}TkExpression({Literal(computed.ColumnName)}, {Root}TkColumnType.{computed.StoreType}, {(computed.IsNullable ? "true" : "false")}, {Literal(computed.Expression)}),");
            }

            source.AppendLine("    };");
            source.AppendLine();
            source.AppendLine($"    static global::System.ReadOnlySpan<{Root}TkExpression> {row}.Expressions => __tkExpressions;");
            source.AppendLine();
        }

        if (table.Indexes.Count > 0)
        {
            source.AppendLine($"    private static readonly {Root}TkIndex<{table.Name}>[] __tkIndexes = new {Root}TkIndex<{table.Name}>[]");
            source.AppendLine("    {");
            foreach (var index in table.Indexes)
            {
                var ordinals = string.Join(", ", index.Fields.Select(static field => field.ToString(CultureInfo.InvariantCulture)));
                source.AppendLine(
                    $"        new {Root}TkIndex<{table.Name}>({Literal(index.Name)}, new int[] {{ {ordinals} }}, {index.Where ?? "null"}{(index.ZoneMinutes > 0 ? ", false, " + index.ZoneMinutes.ToString(CultureInfo.InvariantCulture) : index.Unique ? ", true" : string.Empty)}),");
            }

            source.AppendLine("    };");
            source.AppendLine();
            source.AppendLine($"    static global::System.ReadOnlySpan<{Root}TkIndex<{table.Name}>> {row}.Indexes => __tkIndexes;");
            source.AppendLine();
        }

        EmitConstraints(source, table, row);
        source.AppendLine($"    static void {row}.WriteField(ref {Root}TkKeyWriter writer, {table.Name} row, int field)");
        source.AppendLine("    {");
        source.AppendLine("        switch (field)");
        source.AppendLine("        {");
        for (var i = 0; i < fields.Count; i++)
        {
            var field = fields[i];
            var access = "row." + field.Property;
            source.AppendLine($"            case {i.ToString(CultureInfo.InvariantCulture)}:");
            if (field.IsNullable)
            {
                var local = "__f" + i.ToString(CultureInfo.InvariantCulture);
                source.AppendLine($"                if ({access} is {{ }} {local})");
                source.AppendLine("                {");
                source.AppendLine("                    writer.WritePresent();");
                source.AppendLine($"                    writer.Write({Stored(field, local)});");
                source.AppendLine("                }");
                source.AppendLine("                else");
                source.AppendLine("                {");
                source.AppendLine("                    writer.WriteNull();");
                source.AppendLine("                }");
                source.AppendLine();
            }
            else
            {
                source.AppendLine($"                writer.Write({Stored(field, NotNull(field, access))});");
            }

            source.AppendLine("                break;");
        }

        source.AppendLine("            default:");
        source.AppendLine("                throw new global::System.ArgumentOutOfRangeException(nameof(field));");
        source.AppendLine("        }");
        source.AppendLine("    }");
    }

    private static void EmitConstraints(StringBuilder source, TableModel table, string row)
    {
        if (table.Checks.Count > 0)
        {
            source.AppendLine($"    private static readonly {Root}TkCheck[] __tkChecks = new {Root}TkCheck[]");
            source.AppendLine("    {");
            foreach (var check in table.Checks)
            {
                source.AppendLine($"        new {Root}TkCheck({Literal(check.Name)}, {Literal(check.Text)}),");
            }

            source.AppendLine("    };");
            source.AppendLine();
            source.AppendLine($"    static global::System.ReadOnlySpan<{Root}TkCheck> {row}.Checks => __tkChecks;");
            source.AppendLine();
            source.AppendLine($"    static bool {row}.Check({table.Name} row, int check)");
            source.AppendLine("    {");
            source.AppendLine("        switch (check)");
            source.AppendLine("        {");
            for (var i = 0; i < table.Checks.Count; i++)
            {
                source.AppendLine($"            case {i.ToString(CultureInfo.InvariantCulture)}: return row.{table.Checks[i].Property};");
            }

            source.AppendLine("            default: throw new global::System.ArgumentOutOfRangeException(nameof(check));");
            source.AppendLine("        }");
            source.AppendLine("    }");
            source.AppendLine();
        }

        if (table.ForeignKeys.Count > 0)
        {
            source.AppendLine($"    private static readonly {Root}TkForeignKey[] __tkForeignKeys = new {Root}TkForeignKey[]");
            source.AppendLine("    {");
            foreach (var key in table.ForeignKeys)
            {
                source.AppendLine(
                    $"        new {Root}TkForeignKey({Literal(key.Name)}, {Literal(key.Table)}, {key.Column.ToString(CultureInfo.InvariantCulture)}, {key.Index.ToString(CultureInfo.InvariantCulture)}),");
            }

            source.AppendLine("    };");
            source.AppendLine();
            source.AppendLine($"    static global::System.ReadOnlySpan<{Root}TkForeignKey> {row}.ForeignKeys => __tkForeignKeys;");
            source.AppendLine();
            source.AppendLine($"    static int {row}.WriteForeignKey({table.Name} row, int foreignKey, global::System.Span<byte> destination)");
            source.AppendLine("    {");
            source.AppendLine("        switch (foreignKey)");
            source.AppendLine("        {");
            for (var i = 0; i < table.ForeignKeys.Count; i++)
            {
                var column = table.Columns[table.ForeignKeys[i].Column];
                var access = "row." + column.Property;
                var local = "__k" + i.ToString(CultureInfo.InvariantCulture);
                source.AppendLine($"            case {i.ToString(CultureInfo.InvariantCulture)}:");
                source.AppendLine(column.IsNullable
                    ? $"                return {access} is {{ }} {local} ? {Root}TkKey.Write({local}, destination) : -1;"
                    : $"                return {Root}TkKey.Write({NotNull(column, access)}, destination);");
            }

            source.AppendLine("            default: throw new global::System.ArgumentOutOfRangeException(nameof(foreignKey));");
            source.AppendLine("        }");
            source.AppendLine("    }");
            source.AppendLine();
        }
    }

    /// <summary>A reference that must not be null says which property it was when it is.</summary>
    private static string NotNull(ColumnModel column, string access) =>
        column.IsValueType
            ? access
            : $"({access} ?? throw new global::System.ArgumentNullException({Literal(column.Property.TrimStart('@'))}, \"A column that is not nullable has no value.\"))";

    private static string Stored(ColumnModel column, string value) =>
        column.IsEnum ? $"({column.StoredAs}){value}" : value;

    private static string Literal(string value)
    {
        var literal = new StringBuilder("\"");
        foreach (var character in value)
        {
            literal.Append(character switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                < ' ' or (char)0x2028 or (char)0x2029 => "\\u" + ((int)character).ToString("x4", CultureInfo.InvariantCulture),
                _ => character.ToString(),
            });
        }

        return literal.Append('"').ToString();
    }
}
